export function sigunguList(sido) {
  return Object.keys(REGIONS[sido]?.list || {});
}

export function isKnownRegion(sido, sigungu) {
  return Boolean(REGIONS[sido]?.list?.[sigungu]);
}

export function distanceKm(lat1, lng1, lat2, lng2) {
  const R = 6371;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

// 좌표가 주소상의 시·도 범위와 시·군·구 근처에 있는지 확인한다.
export function coordFitsRegion(sido, sigungu, lat, lng) {
  const r = REGIONS[sido];
  if (!r || typeof lat !== 'number' || typeof lng !== 'number') return false;
  const [s, w, n, e] = r.bbox;
  if (lat < s || lat > n || lng < w || lng > e) return false;
  const c = r.list[sigungu];
  if (!c) return false;
  return distanceKm(lat, lng, c[0], c[1]) <= r.radiusKm;
}
